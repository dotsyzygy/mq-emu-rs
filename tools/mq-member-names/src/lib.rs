//! Generates mq-emu's lists of MacroQuest's datatype member and method names
//! from the `ScopedTypeMember` and `ScopedTypeMethod` lines in its
//! `src/main/datatypes/*.cpp`, plus the members it adds under another name
//! with `AddMember(..., "Name")`. The output is committed to mq-emu, so
//! neither its users nor docs.rs need MacroQuest's source.

use std::collections::BTreeSet;
use std::fmt;
use std::path::{Path, PathBuf};

#[derive(Debug)]
pub struct Error(pub String);

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

/// The workspace root (this crate lives in `tools/mq-member-names`).
pub fn workspace_root() -> PathBuf {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    manifest_dir.parent().and_then(Path::parent).expect("tools/mq-member-names is two levels deep").to_path_buf()
}

/// Where the generated lists are written.
pub fn output_file() -> PathBuf {
    workspace_root().join("crates/mq-emu/src/datatypes/macroquest_members.rs")
}

/// The MacroQuest source selected by `MQ_ROOT`.
pub fn default_root() -> Result<PathBuf, Error> {
    std::env::var_os("MQ_ROOT").map(PathBuf::from).ok_or_else(|| Error("MQ_ROOT is not set".into()))
}

/// Member and method names, each sorted and without repeats.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Names {
    pub members: BTreeSet<String>,
    pub methods: BTreeSet<String>,
}

/// Adds the names declared on one line of a datatype's source. A raw
/// `AddMember` or `AddMethod` must name its member with a string literal, so
/// that one this can't read is an error rather than a name left out.
pub fn scan_line(line: &str, names: &mut Names) -> Result<(), Error> {
    let code = line.split("//").next().unwrap_or("");
    for (macro_name, is_method) in [("TypeMember(", false), ("TypeMethod(", true)] {
        for (start, _) in code.match_indices(macro_name) {
            let args = &code[start + macro_name.len()..];
            let args = args.split(')').next().unwrap_or("");
            let name = args.rsplit(',').next().unwrap_or("").trim();
            insert(names, is_method, name, line)?;
        }
    }
    for (call, is_method) in [("AddMember(", false), ("AddMethod(", true)] {
        for (start, _) in code.match_indices(call) {
            let args = &code[start + call.len()..];
            let name = args.split('"').nth(1).filter(|_| args.contains(", \"") || args.contains(",\""));
            let Some(name) = name else {
                return Err(Error(format!("can't read the name in `{}`", line.trim())));
            };
            insert(names, is_method, name, line)?;
        }
    }
    Ok(())
}

fn insert(names: &mut Names, is_method: bool, name: &str, line: &str) -> Result<(), Error> {
    if !valid_name(name) {
        return Err(Error(format!("`{name}` isn't a member name, in `{}`", line.trim())));
    }
    let list = if is_method { &mut names.methods } else { &mut names.members };
    list.insert(name.to_owned());
    Ok(())
}

/// Letters, digits and `_`, starting with a letter, as mq-emu's member names.
fn valid_name(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_alphabetic()) && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Every name in the `*.cpp` files of `root`'s `src/main/datatypes`.
pub fn scan(root: &Path) -> Result<Names, Error> {
    let dir = root.join("src/main/datatypes");
    let entries = std::fs::read_dir(&dir).map_err(|e| Error(format!("{}: {e}", dir.display())))?;
    let mut files: Vec<PathBuf> = entries.filter_map(|entry| Some(entry.ok()?.path())).filter(|path| path.extension().is_some_and(|ext| ext == "cpp")).collect();
    files.sort();
    let mut names = Names::default();
    for file in files {
        let text = std::fs::read_to_string(&file).map_err(|e| Error(format!("{}: {e}", file.display())))?;
        for line in text.lines() {
            scan_line(line, &mut names).map_err(|Error(e)| Error(format!("{}: {e}", file.display())))?;
        }
    }
    if names.members.is_empty() {
        return Err(Error(format!("no members found in {}", dir.display())));
    }
    Ok(names)
}

/// The Rust source of the lists.
pub fn emit(names: &Names) -> String {
    let mut out = String::from(
        "// Generated by `cargo run -p mq-member-names` from MacroQuest's src/main/datatypes. Don't edit.\n\n\
         /// Every member name of MacroQuest's own datatypes, sorted, each once\n\
         /// (`ID` is on many types), including the second names some members\n\
         /// have (`SongCap`). For [`DataTypeDef::any_member`](crate::DataTypeDef::any_member)\n\
         /// on a type that passes MacroQuest's paths through, since Lua can read\n\
         /// only listed names. Methods aren't here: see [`MACROQUEST_METHODS`].\n\
         #[rustfmt::skip]\n\
         pub const MACROQUEST_MEMBERS: &[&str] = &[\n",
    );
    for name in &names.members {
        out.push_str(&format!("    \"{name}\",\n"));
    }
    out.push_str(
        "];\n\n\
         /// Every method name of MacroQuest's own datatypes (`${Me.Buff[1].Remove}`),\n\
         /// sorted, each once. Reading one acts, so a type passing paths through\n\
         /// to another client may want to refuse these. A name can be a member\n\
         /// on one type and a method on another, and so in both lists.\n\
         #[rustfmt::skip]\n\
         pub const MACROQUEST_METHODS: &[&str] = &[\n",
    );
    for name in &names.methods {
        out.push_str(&format!("    \"{name}\",\n"));
    }
    out.push_str("];\n");
    out
}

/// The generated source for the MacroQuest source at `root`.
pub fn generate(root: &Path) -> Result<String, Error> {
    Ok(emit(&scan(root)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scanned(lines: &[&str]) -> Result<Names, Error> {
        let mut names = Names::default();
        for line in lines {
            scan_line(line, &mut names)?;
        }
        Ok(names)
    }

    fn set(names: &[&str]) -> BTreeSet<String> {
        names.iter().map(|name| (*name).to_owned()).collect()
    }

    #[test]
    fn every_way_macroquest_declares_a_member() {
        let names = scanned(&[
            "\tScopedTypeMember(SpawnMembers, ID);",
            "    ScopedTypeMember( SpawnMembers , Level );",
            "\tTypeMember(Active);",
            "\tScopedTypeMethod(AchievementTypeMethods, Inspect);",
            "\tAddMember(static_cast<int>(EverQuestMembers::xScreenMode), \"ScreenMode\");",
            "\tScopedTypeMember(BuffMembers, ID); // again, on another type",
            "\t// ScopedTypeMember(SpawnMembers, Commented);",
            "\tint x = 1;",
        ])
        .unwrap();
        assert_eq!(names.members, set(&["Active", "ID", "Level", "ScreenMode"]));
        assert_eq!(names.methods, set(&["Inspect"]));
    }

    /// Negative: a raw `AddMember` without a string literal would otherwise be
    /// a member silently left off the list.
    #[test]
    fn a_name_it_cant_read_is_an_error() {
        let err = scanned(&["\tAddMember(static_cast<int>(SpellMembers::Cap), name);"]).unwrap_err();
        assert!(err.to_string().contains("can't read the name"), "{err}");
        let err = scanned(&["\tScopedTypeMember(SpawnMembers, 2nd);"]).unwrap_err();
        assert!(err.to_string().contains("`2nd` isn't a member name"), "{err}");
    }

    #[test]
    fn output_is_sorted_and_each_list_separate() {
        let names = scanned(&["ScopedTypeMember(A, Zeta);", "ScopedTypeMember(A, Alpha);", "ScopedTypeMethod(A, Remove);"]).unwrap();
        let out = emit(&names);
        let members = &out[out.find("MACROQUEST_MEMBERS").unwrap()..out.find("MACROQUEST_METHODS: &").unwrap()];
        assert!(members.find("\"Alpha\"").unwrap() < members.find("\"Zeta\"").unwrap());
        assert!(!members.contains("\"Remove\""));
        assert!(out[out.find("MACROQUEST_METHODS: &").unwrap()..].contains("\"Remove\""));
    }
}
