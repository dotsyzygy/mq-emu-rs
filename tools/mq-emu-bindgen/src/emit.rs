//! Turns a [`Model`] into Rust source.
//!
//! Every record becomes an opaque, `UnsafeCell`-wrapped byte block with
//! accessor methods, rather than a struct with public fields:
//! - the game mutates these objects behind Rust's back, so plain `&` field
//!   access would be unsound, while `UnsafeCell` makes shared access legal;
//! - unions, bitfields, packed layouts and flattened (virtual) bases all reduce
//!   to "read a value at an offset", so they need no special Rust layout;
//! - C++ `bool` is read as a byte and compared with 0, so stray values in game
//!   memory can't produce an invalid Rust `bool`.
//!
//! Accessor names keep the C++ member names, as befits a `-sys` crate.

use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;

use crate::model::{Field, Model, Prim, Record, Ty, TypeId, is_anonymous};

const HEADER: &str = "\
// @generated by mq-emu-bindgen from eqlib.pdb. Do not edit by hand;
// change crates/mq-emu-sys/layouts.txt and run `cargo run -p mq-emu-bindgen`.

use core::cell::UnsafeCell;
use core::ffi::{c_char, c_void};
use core::marker::{PhantomData, PhantomPinned};

use super::{FieldInfo, RecordInfo};

#[inline(always)]
unsafe fn read<T>(base: *mut u8, offset: usize) -> T {
    unsafe { base.add(offset).cast::<T>().read_unaligned() }
}

#[inline(always)]
unsafe fn write<T>(base: *mut u8, offset: usize, value: T) {
    unsafe { base.add(offset).cast::<T>().write_unaligned(value) }
}

#[inline(always)]
unsafe fn at<'a, T>(base: *mut u8, offset: usize) -> &'a T {
    unsafe { &*base.add(offset).cast::<T>() }
}
";

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "gen",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

/// Names that can't even be raw identifiers.
const RESERVED: &[&str] = &["self", "Self", "super", "crate", "_"];

/// Converts arbitrary C++ spelling into a Rust identifier (without keyword
/// handling). Runs of other characters become one `_`; underscores that were
/// already in the name are kept, so `__vfptr` stays `__vfptr`.
pub fn sanitize(name: &str) -> String {
    // (char, inserted by us)
    let mut chars: Vec<(char, bool)> = Vec::with_capacity(name.len());
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            chars.push((c, false));
        } else if chars.last() != Some(&('_', true)) {
            chars.push(('_', true));
        }
    }
    while chars.first().is_some_and(|(_, inserted)| *inserted) {
        chars.remove(0);
    }
    while chars.last().is_some_and(|(_, inserted)| *inserted) {
        chars.pop();
    }
    let out: String = chars.into_iter().map(|(c, _)| c).collect();
    match out.chars().next() {
        None => "_unnamed".to_owned(),
        Some(c) if c.is_ascii_digit() => format!("_{out}"),
        Some(_) => out,
    }
}

/// Makes `name` usable as a method or constant name.
pub fn ident(name: &str) -> String {
    let base = sanitize(name);
    if RESERVED.contains(&base.as_str()) {
        format!("{base}_")
    } else if KEYWORDS.contains(&base.as_str()) {
        format!("r#{base}")
    } else {
        base
    }
}

/// Rust names for every emitted type, unique across records, enums and opaques.
struct Names {
    types: HashMap<TypeId, String>,
}

impl Names {
    fn new(model: &Model) -> Names {
        let mut used = HashSet::new();
        let mut types = HashMap::new();
        fn claim(used: &mut HashSet<String>, types: &mut HashMap<TypeId, String>, id: TypeId, wanted: String) {
            let mut name = wanted.clone();
            let mut n = 2;
            while !used.insert(name.clone()) {
                name = format!("{wanted}_{n}");
                n += 1;
            }
            types.insert(id, name);
        }

        // Named types first, in name order, so their names never get suffixes
        // because of an anonymous type.
        let mut named: Vec<(&str, TypeId)> = model
            .records
            .iter()
            .map(|(id, r)| (r.cpp_name.as_str(), *id))
            .chain(model.enums.iter().map(|(id, e)| (e.cpp_name.as_str(), *id)))
            .chain(model.opaque.iter().map(|(id, name)| (name.as_str(), *id)))
            .filter(|(name, _)| !is_anonymous(name))
            .collect();
        named.sort();
        for (name, id) in named {
            claim(&mut used, &mut types, id, sanitize(name));
        }

        // Anonymous records are named after the member that contains them. A
        // parent may itself be anonymous, so resolve in dependency order.
        let mut pending: Vec<TypeId> = model
            .records
            .iter()
            .filter(|(_, r)| is_anonymous(&r.cpp_name))
            .map(|(id, _)| *id)
            .chain(model.enums.iter().filter(|(_, e)| is_anonymous(&e.cpp_name)).map(|(id, _)| *id))
            .chain(model.opaque.iter().filter(|(_, n)| is_anonymous(n)).map(|(id, _)| *id))
            .collect();
        while !pending.is_empty() {
            let before = pending.len();
            let mut waiting = Vec::new();
            for id in pending.drain(..) {
                let hint = model.records.get(&id).and_then(|r| r.parent_hint.as_ref());
                let wanted = match hint {
                    Some((parent, member)) => match types.get(parent) {
                        Some(parent_name) => format!("{parent_name}_{}", sanitize(member)),
                        None => {
                            waiting.push(id);
                            continue;
                        }
                    },
                    None => format!("Anonymous_{id:x}"),
                };
                claim(&mut used, &mut types, id, wanted);
            }
            // No progress means the remaining parents can never be named (a cycle,
            // or a parent outside the model); fall back to index-based names.
            if waiting.len() == before {
                for id in waiting.drain(..) {
                    claim(&mut used, &mut types, id, format!("Anonymous_{id:x}"));
                }
            }
            pending = waiting;
        }
        Names { types }
    }

    fn of(&self, id: TypeId) -> &str {
        &self.types[&id]
    }
}

pub fn emit(model: &Model) -> String {
    let names = Names::new(model);
    let mut out = String::from(HEADER);

    let mut records: Vec<(&str, TypeId, &Record)> =
        model.records.iter().map(|(id, r)| (names.of(*id), *id, r)).collect();
    records.sort_by_key(|(name, _, _)| *name);

    let mut field_rows = Vec::new();
    for (name, _, record) in &records {
        let accessors = accessor_names(record);
        emit_record(&mut out, model, &names, name, record, &accessors);
        for (field, accessor) in record.fields.iter().zip(&accessors) {
            field_rows.push((record.cpp_name.as_str(), field, accessor.clone()));
        }
    }

    let mut enums: Vec<(&str, TypeId)> = model.enums.keys().map(|id| (names.of(*id), *id)).collect();
    enums.sort();
    for (name, id) in enums {
        emit_enum(&mut out, model, name, id);
    }

    let mut opaques: Vec<&str> = model.opaque.keys().map(|id| names.of(*id)).collect();
    opaques.sort();
    for name in opaques {
        let _ = write!(
            out,
            "\n/// Opaque: only reached through pointers from generated records.\n\
             #[repr(C)]\n\
             pub struct {name} {{\n    _opaque: [u8; 0],\n    _marker: PhantomData<(*mut u8, PhantomPinned)>,\n}}\n"
        );
    }

    out.push_str("\n/// Every generated record, keyed by its C++ name.\npub static RECORDS: &[RecordInfo] = &[\n");
    for (name, _, record) in &records {
        let _ = writeln!(
            out,
            "    RecordInfo {{ name: {:?}, rust_name: {:?}, size: {:#x} }},",
            record.cpp_name, name, record.size
        );
    }
    out.push_str("];\n");

    out.push_str("\n/// Every generated field accessor and where it reads from.\npub static FIELDS: &[FieldInfo] = &[\n");
    for (record, field, accessor) in field_rows {
        let bits = field.bits.map_or("None".to_owned(), |b| format!("Some(({}, {}))", b.position, b.length));
        let _ = writeln!(
            out,
            "    FieldInfo {{ record: {record:?}, field: {:?}, accessor: {:?}, declared_in: {:?}, offset: {:#x}, decl_offset: {:#x}, size: {:#x}, bits: {bits} }},",
            field.name,
            accessor.trim_start_matches("r#"),
            field.declared_in,
            field.offset,
            field.decl_offset,
            model.size_of(&field.ty),
        );
    }
    out.push_str("];\n");
    out
}

/// Picks a unique getter name per field. Setters are `set_<getter>`, so both
/// namespaces are checked together.
fn accessor_names(record: &Record) -> Vec<String> {
    let mut used: HashSet<String> = HashSet::new();
    let mut names = Vec::with_capacity(record.fields.len());
    for field in &record.fields {
        let candidates = [
            ident(&field.name),
            ident(&format!("{}_{}", field.declared_in, field.name)),
            ident(&format!("{}_{}_{:x}", field.declared_in, field.name, field.offset)),
        ];
        let chosen = candidates
            .into_iter()
            .find(|c| {
                let bare = c.trim_start_matches("r#");
                !used.contains(bare) && !used.contains(&format!("set_{bare}"))
            })
            .expect("offset-qualified accessor names are unique");
        let bare = chosen.trim_start_matches("r#").to_owned();
        used.insert(format!("set_{bare}"));
        used.insert(bare);
        names.push(chosen);
    }
    names
}

fn prim_rust(p: Prim) -> &'static str {
    match p {
        Prim::Bool | Prim::U8 => "u8",
        Prim::CChar => "c_char",
        Prim::I8 => "i8",
        Prim::I16 => "i16",
        Prim::U16 => "u16",
        Prim::I32 => "i32",
        Prim::U32 => "u32",
        Prim::I64 => "i64",
        Prim::U64 => "u64",
        Prim::F32 => "f32",
        Prim::F64 => "f64",
    }
}

fn unsigned_of(p: Prim) -> &'static str {
    match p.size() {
        1 => "u8",
        2 => "u16",
        4 => "u32",
        _ => "u64",
    }
}

/// The Rust spelling of a value of `ty` (C++ `bool` inside aggregates is `u8`).
fn rust_ty(model: &Model, names: &Names, ty: &Ty) -> String {
    match ty {
        Ty::Prim(p) => prim_rust(*p).to_owned(),
        Ty::Void | Ty::Function => "c_void".to_owned(),
        Ty::Pointer(inner) => format!("*mut {}", rust_ty(model, names, inner)),
        Ty::Array(element, bytes) => {
            let size = model.size_of(element);
            format!("[{}; {}]", rust_ty(model, names, element), bytes.checked_div(size).unwrap_or(0))
        }
        Ty::Record(id) | Ty::Enum(id) => names.of(*id).to_owned(),
        Ty::Bytes(n) => format!("[u8; {n}]"),
    }
}

/// True if values of `ty` can be copied out (no generated records inside).
fn is_copy(ty: &Ty) -> bool {
    match ty {
        Ty::Prim(_) | Ty::Pointer(_) | Ty::Enum(_) | Ty::Bytes(_) => true,
        Ty::Array(element, _) => is_copy(element),
        Ty::Record(_) | Ty::Void | Ty::Function => false,
    }
}

fn emit_record(out: &mut String, model: &Model, names: &Names, name: &str, record: &Record, accessors: &[String]) {
    let kind = if record.is_union { "union" } else { "class" };
    let _ = write!(
        out,
        "\n/// C++ {kind} `{}` ({:#x} bytes).\n\
         #[repr(C)]\n\
         pub struct {name} {{\n    _bytes: UnsafeCell<[u8; {:#x}]>,\n    _pin: PhantomData<PhantomPinned>,\n}}\n\n\
         impl {name} {{",
        record.cpp_name, record.size, record.size
    );

    for (field, getter) in record.fields.iter().zip(accessors) {
        let setter = format!("set_{}", getter.trim_start_matches("r#"));
        let doc = field_doc(field);
        let offset = format!("{:#x}", field.offset);
        let base = "self._bytes.get().cast()";

        if let Some(bits) = field.bits {
            let storage = match &field.ty {
                Ty::Prim(p) => *p,
                Ty::Enum(id) => model.enums[id].underlying,
                other => {
                    let _ = write!(out, "\n    // {}: bitfield of unsupported type {other:?}\n", field.name);
                    continue;
                }
            };
            let raw = unsigned_of(storage);
            let mask = if bits.length >= 64 { u64::MAX } else { (1u64 << bits.length) - 1 };
            let (ret, get_expr, set_value) = if storage == Prim::Bool && bits.length == 1 {
                ("bool", "bits != 0".to_owned(), format!("{raw}::from(value)"))
            } else {
                (raw, "bits".to_owned(), "value".to_owned())
            };
            let _ = write!(
                out,
                "\n{doc}    #[inline]\n    pub fn {getter}(&self) -> {ret} {{\n        \
                 let raw: {raw} = unsafe {{ read({base}, {offset}) }};\n        \
                 let bits = (raw >> {pos}) & {mask:#x};\n        {get_expr}\n    }}\n\n\
                 {doc}    #[inline]\n    pub fn {setter}(&self, value: {ret}) {{\n        \
                 let raw: {raw} = unsafe {{ read({base}, {offset}) }};\n        \
                 let raw = (raw & !({mask:#x} << {pos})) | (({set_value} & {mask:#x}) << {pos});\n        \
                 unsafe {{ write({base}, {offset}, raw) }}\n    }}\n",
                pos = bits.position,
            );
            continue;
        }

        match &field.ty {
            Ty::Prim(Prim::Bool) => {
                let _ = write!(
                    out,
                    "\n{doc}    #[inline]\n    pub fn {getter}(&self) -> bool {{\n        unsafe {{ read::<u8>({base}, {offset}) != 0 }}\n    }}\n\n\
                     {doc}    #[inline]\n    pub fn {setter}(&self, value: bool) {{\n        unsafe {{ write({base}, {offset}, u8::from(value)) }}\n    }}\n"
                );
            }
            ty if is_copy(ty) => {
                let rust = rust_ty(model, names, ty);
                let _ = write!(
                    out,
                    "\n{doc}    #[inline]\n    pub fn {getter}(&self) -> {rust} {{\n        unsafe {{ read({base}, {offset}) }}\n    }}\n\n\
                     {doc}    #[inline]\n    pub fn {setter}(&self, value: {rust}) {{\n        unsafe {{ write({base}, {offset}, value) }}\n    }}\n"
                );
            }
            Ty::Record(id) => {
                let rust = names.of(*id);
                let _ = write!(
                    out,
                    "\n{doc}    #[inline]\n    pub fn {getter}(&self) -> &{rust} {{\n        unsafe {{ at({base}, {offset}) }}\n    }}\n"
                );
            }
            Ty::Array(..) => {
                // Arrays of records (possibly multi-dimensional): index the flattened elements.
                let mut element = &field.ty;
                while let Ty::Array(inner, _) = element {
                    element = inner;
                }
                let Ty::Record(id) = element else { unreachable!("non-copy array of {element:?}") };
                let element_size = model.size_of(element);
                let count = model.size_of(&field.ty).checked_div(element_size).unwrap_or(0);
                let rust = names.of(*id);
                let _ = write!(
                    out,
                    "\n{doc}    /// Indexes the {count} elements in memory order.\n    #[inline]\n    \
                     pub fn {getter}(&self, index: usize) -> &{rust} {{\n        \
                     assert!(index < {count}, \"index out of bounds\");\n        \
                     unsafe {{ at({base}, {offset} + index * {element_size:#x}) }}\n    }}\n"
                );
            }
            other => {
                let _ = write!(out, "\n    // {}: unsupported member type {other:?}\n", field.name);
            }
        }
    }
    out.push_str("}\n");
}

fn field_doc(field: &Field) -> String {
    let bits = field.bits.map_or(String::new(), |b| format!(", bits {}..{}", b.position, b.position + b.length));
    format!(
        "    /// `{}::{}` at {:#x}{bits} ({:#x} within `{}`).\n",
        field.declared_in, field.name, field.offset, field.decl_offset, field.declared_in
    )
}

fn emit_enum(out: &mut String, model: &Model, name: &str, id: TypeId) {
    let e = &model.enums[&id];
    let repr = prim_rust(e.underlying);
    let _ = write!(
        out,
        "\n/// C++ enum `{}`. A newtype rather than a Rust enum, since game memory may hold\n\
         /// values that aren't listed.\n\
         #[repr(transparent)]\n\
         #[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\n\
         pub struct {name}(pub {repr});\n",
        e.cpp_name
    );
    if e.values.is_empty() {
        return;
    }
    let _ = write!(out, "\nimpl {name} {{\n");
    let mut used = HashSet::new();
    for (value_name, value) in &e.values {
        let mut constant = ident(value_name);
        let mut n = 2;
        while !used.insert(constant.clone()) {
            constant = format!("{}_{n}", ident(value_name));
            n += 1;
        }
        let _ = writeln!(out, "    pub const {constant}: Self = Self({});", literal(*value, e.underlying));
    }
    out.push_str("}\n");
}

/// Renders an enumerator value as a literal of the enum's underlying type.
fn literal(value: i128, prim: Prim) -> String {
    let bits = prim.size() * 8;
    let mask = (1i128 << bits) - 1;
    let unsigned = value & mask;
    let signed = matches!(prim, Prim::I8 | Prim::I16 | Prim::I32 | Prim::I64 | Prim::CChar);
    if signed && unsigned >> (bits - 1) == 1 {
        (unsigned - (1i128 << bits)).to_string()
    } else {
        unsigned.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitizes_template_and_namespace_names() {
        assert_eq!(sanitize("TListNode<PlayerClient>"), "TListNode_PlayerClient");
        assert_eq!(sanitize("TCircularBuffer<SDoCollisionMovementStats,20>"), "TCircularBuffer_SDoCollisionMovementStats_20");
        assert_eq!(sanitize("ArrayClass2<unsigned int>"), "ArrayClass2_unsigned_int");
        assert_eq!(sanitize("std::basic_string<char>"), "std_basic_string_char");
        assert_eq!(sanitize("<unnamed-tag>"), "unnamed_tag");
        assert_eq!(sanitize("3D"), "_3D");
        assert_eq!(sanitize("<>"), "_unnamed");
    }

    #[test]
    fn sanitize_keeps_real_underscores() {
        assert_eq!(sanitize("__vfptr"), "__vfptr");
        assert_eq!(sanitize("_flags_"), "_flags_");
        assert_eq!(sanitize("Base___vfptr"), "Base___vfptr");
        assert_eq!(sanitize("a__b<c>"), "a__b_c");
    }

    #[test]
    fn idents_escape_keywords() {
        assert_eq!(ident("Type"), "Type");
        assert_eq!(ident("type"), "r#type");
        assert_eq!(ident("self"), "self_");
        assert_eq!(ident("Self"), "Self_");
    }

    #[test]
    fn literals_respect_underlying_type() {
        assert_eq!(literal(-1, Prim::I32), "-1");
        assert_eq!(literal(-1, Prim::U32), "4294967295");
        assert_eq!(literal(0xffff_ffff, Prim::I32), "-1");
        assert_eq!(literal(255, Prim::U8), "255");
        assert_eq!(literal(5, Prim::I8), "5");
    }

    fn field(name: &str, declared_in: &str, offset: u64) -> Field {
        Field { name: name.into(), declared_in: declared_in.into(), offset, decl_offset: offset, ty: Ty::Prim(Prim::I32), bits: None }
    }

    #[test]
    fn accessor_names_disambiguate_collisions() {
        let record = Record {
            cpp_name: "Derived".into(),
            size: 0x20,
            is_union: false,
            fields: vec![
                field("__vfptr", "Base", 0),
                field("__vfptr", "Other", 8),
                field("x", "Derived", 0x10),
                field("set_x", "Derived", 0x14),
                field("type", "Derived", 0x18),
                field("x", "Derived", 0x1c),
            ],
            parent_hint: None,
        };
        assert_eq!(
            accessor_names(&record),
            ["__vfptr", "Other___vfptr", "x", "Derived_set_x", "r#type", "Derived_x"]
        );
    }
}
